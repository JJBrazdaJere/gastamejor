-- 005_ingresos.sql
-- Ingresos DIARIOS de cada usuario. El total de un mes es la suma de los
-- ingresos de ese mes (mas el "ingreso_fijo_mensual" de la cuenta, si tiene).
--
-- ON DELETE CASCADE: si se elimina la cuenta, se borran sus ingresos.

BEGIN;

CREATE TABLE ingresos (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id  integer      NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
    fecha       date         NOT NULL DEFAULT CURRENT_DATE,
    monto       numeric(14,2) NOT NULL,
    descripcion varchar(120),
    creado_en   timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ingresos_monto_no_negativo CHECK (monto >= 0)
);

-- Buscar los ingresos de un usuario en un rango de fechas (un mes) rapido.
CREATE INDEX ingresos_cliente_fecha_idx ON ingresos (cliente_id, fecha);

COMMIT;
