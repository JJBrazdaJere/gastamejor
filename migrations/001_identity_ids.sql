-- 001_identity_ids.sql
-- Agrega autoincremento (IDENTITY) a clientes, empleados y ventas.
-- productos y proveedores ya lo tienen.
-- detalle_ventas NO aplica: su PK es compuesta (venta_id, producto_id).
--
-- Se usa BY DEFAULT (no ALWAYS) para permitir, si hiciera falta, cargar un id
-- explicito (por ejemplo en migraciones o tests).

BEGIN;

ALTER TABLE clientes  ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE empleados ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE ventas    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

-- Dejar la secuencia despues del id maximo que ya existe.
SELECT setval(pg_get_serial_sequence('clientes', 'id'),  COALESCE((SELECT MAX(id) FROM clientes), 0) + 1, false);
SELECT setval(pg_get_serial_sequence('empleados', 'id'), COALESCE((SELECT MAX(id) FROM empleados), 0) + 1, false);
SELECT setval(pg_get_serial_sequence('ventas', 'id'),    COALESCE((SELECT MAX(id) FROM ventas), 0) + 1, false);

COMMIT;
